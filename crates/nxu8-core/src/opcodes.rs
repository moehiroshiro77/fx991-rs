//! The opcode table: how each 16-bit halfword decodes.
//!
//! Each entry names the handler, its operand layout, and the hint flags that say
//! whether an operand is a byte or a word, immediate or register.
//!
//! This is data, not code.  It was derived from the ROM's verified disassembly and
//! is checked by `dispatch_digest`, which fails if the table and the decoder ever
//! disagree.  Editing it by hand is possible but the digest will notice.

//! Opcode table: the encoding of every instruction, from the OKI manual's
//! instruction descriptions.
//!
//! Each row is the handler name, the hint flags, the base opcode, and the
//! two operand descriptors `(register_size, mask, shift)`.  `register_size`
//! of 0 marks an immediate whose value is the masked opcode bits.

